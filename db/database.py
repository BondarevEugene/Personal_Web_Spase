from sqlalchemy import create_engine
from sqlalchemy.orm import declarative_base
from sqlalchemy.orm import sessionmaker

from core.config import DATABASE_URL

# ==============================================================================
# ENGINE CONFIGURATION
# ==============================================================================

engine_options = {}

# SQLite требует специальный параметр
if DATABASE_URL.startswith("sqlite"):
    engine_options["connect_args"] = {
        "check_same_thread": False
    }

engine = create_engine(
    DATABASE_URL,
    future=True,
    echo=False,
    **engine_options
)

# ==============================================================================
# SESSION FACTORY
# ==============================================================================

SessionLocal = sessionmaker(
    autocommit=False,
    autoflush=False,
    bind=engine
)

# ==============================================================================
# DECLARATIVE BASE
# ==============================================================================

Base = declarative_base()

# ==============================================================================
# FASTAPI DEPENDENCY
# ==============================================================================

def get_db():
    """
    Dependency для FastAPI.

    Для каждого HTTP запроса создается
    отдельная SQLAlchemy Session.

    После завершения запроса
    соединение автоматически закрывается.
    """

    db = SessionLocal()

    try:
        yield db

    finally:
        db.close()


# ==============================================================================
# INITIALIZATION
# ==============================================================================

def initialize_database():

    """
    Создает все отсутствующие таблицы.

    Вызывается один раз
    во время старта приложения.
    """

    Base.metadata.create_all(bind=engine)