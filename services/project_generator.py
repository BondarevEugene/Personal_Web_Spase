from __future__ import annotations

import io
import zipfile
from pathlib import Path
from datetime import datetime

from core.compiler.exporter import Exporter


class ProjectGenerator:
    """
    Центральный генератор проектов OMNIFACTORY.

    Генератор ничего не знает про FastAPI.

    Его могут использовать:

        • REST API

        • Desktop

        • CLI

        • Telegram

        • AI Agent

        • MCP
    """

    # ----------------------------------------------------------------------

    def __init__(
            self,
            bot_code: str = "",
            selected_modules: list | None = None
    ):

        self.bot_code = bot_code

        self.modules = selected_modules or []

        self.exporter = Exporter()

    # ----------------------------------------------------------------------

    @property
    def requirements(self) -> str:
        """
        Формирует requirements.txt
        """

        packages = [

            "fastapi",

            "uvicorn",

            "jinja2",

            "python-dotenv"

        ]

        if "telegram" in self.modules:

            packages.append("aiogram")

        if "rag" in self.modules:

            packages.extend([

                "langchain",

                "chromadb"

            ])

        return "\n".join(sorted(set(packages)))

    # ----------------------------------------------------------------------

    @property
    def dockerfile(self) -> str:

        return """
FROM python:3.12-slim

WORKDIR /app

COPY . .

RUN pip install -r requirements.txt

CMD ["python", "main.py"]
""".strip()

    # ----------------------------------------------------------------------

    @property
    def readme(self) -> str:

        return f"""
# OMNIFACTORY PROJECT

Generated:

{datetime.utcnow()}

---

This package was generated automatically.

Deployment:

docker build -t omnifactory .

docker run omnifactory

---

Generated by OMNIFACTORY Enterprise Compiler.
""".strip()

    # ----------------------------------------------------------------------

    def create_deployment_package(self):

        """
        Создает ZIP архив проекта.
        """

        buffer = io.BytesIO()

        with zipfile.ZipFile(
                buffer,
                "w",
                zipfile.ZIP_DEFLATED
        ) as archive:

            # ----------------------------------------------------------

            archive.writestr(

                "main.py",

                self.bot_code

            )

            # ----------------------------------------------------------

            archive.writestr(

                "requirements.txt",

                self.requirements

            )

            # ----------------------------------------------------------

            archive.writestr(

                "Dockerfile",

                self.dockerfile

            )

            # ----------------------------------------------------------

            archive.writestr(

                "README.md",

                self.readme

            )

        buffer.seek(0)

        return buffer.getvalue()

    # ----------------------------------------------------------------------

    def export_project(
            self,
            project_directory: str
    ):

        """
        Экспорт проекта на диск.

        Пока создает базовую структуру.

        Далее Exporter возьмет управление полностью.
        """

        project_path = Path(project_directory)

        self.exporter.export(project_path)

        return {

            "success": True,

            "project": str(project_path)

        }

    # ----------------------------------------------------------------------
    # WORKSPACE
    # ----------------------------------------------------------------------

    def prepare_workspace(self, project):

        """
        Создает рабочую директорию проекта.

        Workspace имеет вид:

            workspace/
                project_name/

        """

        from pathlib import Path

        workspace = Path("workspace") / project.name

        workspace.mkdir(

            parents=True,

            exist_ok=True

        )

        return workspace
