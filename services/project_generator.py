# ProjectGenerator является центральным генератором проекта.
#
# Он отвечает за создание полного Deployment Package,
# который может быть сразу передан:
#
#     • Docker
#     • VPS
#     • Telegram
#     • Desktop
#     • Android
#
# На данном этапе генератор создает:
#
#     ✔ main.py
#     ✔ requirements.txt
#     ✔ Dockerfile
#     ✔ README.md
#
# В следующих версиях будут добавлены:
#
#     • runtime.json
#     • manifest.json
#     • docker-compose.yml
#     • .env.example
#     • .gitignore
#     • структура проекта
#
