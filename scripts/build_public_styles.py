"""Deterministic homepage CSS bundler with a no-drift verification mode.

The original stylesheets remain separate and editable. The public homepage
uses one concatenated CSS file in the exact authored cascade order.

Usage:
    python -m scripts.build_public_styles --write
    python -m scripts.build_public_styles --check
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STATIC = ROOT / "omni_site" / "static"
BUNDLE = STATIC / "home.bundle.css"

HOME_CSS = (
    "site.css",
    "platform.css",
    "founders.css",
    "unified_shell.css",
    "public_growth.css",
    "demo_home.css",
    "case_home.css",
    "services_home.css",
    "trust_home.css",
    "visual_excellence.css",
)


def render_bundle() -> bytes:
    blocks: list[str] = []
    for index, name in enumerate(HOME_CSS):
        source = STATIC / name
        text = source.read_text(encoding="utf-8")
        # CSS @import must come before ordinary CSS rules. The only existing
        # @import belongs to the first sheet, so source order is preserved.
        if index and "@import" in text:
            raise ValueError(f"Late CSS import cannot be bundled: {name}")
        if "url(../" in text or "url('./" in text or 'url("./' in text:
            raise ValueError(f"Relative URL requires rewriting: {name}")
        blocks.append(f"/* BEGIN {name} */\n{text.rstrip()}\n/* END {name} */")
    body = "\n\n".join(blocks) + "\n"
    checksum = hashlib.sha256(body.encode("utf-8")).hexdigest()
    header = (
        "/* Generated by scripts.build_public_styles; DO NOT EDIT.\n"
        "   Source order: " + ", ".join(HOME_CSS) + "\n"
        "   SHA256: " + checksum + "\n"
        "   Run: python -m scripts.build_public_styles --write\n"
        "*/\n"
    )
    return (header + body).encode("utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render_bundle()
    if args.write:
        BUNDLE.write_bytes(expected)
        print(f"Wrote {BUNDLE.name}: {len(expected)} bytes")
        return 0
    if not BUNDLE.exists() or BUNDLE.read_bytes() != expected:
        print(
            "Homepage CSS bundle is stale; "
            "run: python -m scripts.build_public_styles --write"
        )
        return 1
    print(f"Homepage CSS bundle is current: {len(expected)} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
